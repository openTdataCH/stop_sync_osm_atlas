"""Alembic environment for the application's single PostGIS database."""

import logging
from logging.config import fileConfig

from alembic import context
from flask import current_app
from geoalchemy2 import alembic_helpers

config = context.config
fileConfig(config.config_file_name)
logger = logging.getLogger('alembic.env')

target_db = current_app.extensions['migrate'].db
config.set_main_option(
    'sqlalchemy.url',
    target_db.engine.url.render_as_string(hide_password=False).replace('%', '%%'),
)

def include_object(obj, name, type_, reflected, compare_to):
    # Tables that only the database has belong to PostGIS and its extensions
    # (spatial_ref_sys, the TIGER geocoder); autogenerate must never drop them.
    if type_ == 'table' and reflected and compare_to is None:
        return False
    return alembic_helpers.include_object(obj, name, type_, reflected, compare_to)


def process_revision_directives(migration_context, revision, directives):
    # Skip empty autogenerated revisions, then let GeoAlchemy write its spatial operations.
    if getattr(config.cmd_opts, 'autogenerate', False) and directives[0].upgrade_ops.is_empty():
        directives[:] = []
        logger.info('No changes in schema detected.')
        return
    alembic_helpers.writer.process_revision_directives(migration_context, revision, directives)


def configure_args(**kwargs):
    return {
        'target_metadata': target_db.metadata,
        'include_object': include_object,
        'process_revision_directives': process_revision_directives,
        'render_item': alembic_helpers.render_item,
        **current_app.extensions['migrate'].configure_args,
        # Batch mode exists for SQLite; PostGIS alters tables directly.
        'render_as_batch': False,
        **kwargs,
    }


if context.is_offline_mode():
    context.configure(**configure_args(url=config.get_main_option('sqlalchemy.url'), literal_binds=True))
    with context.begin_transaction():
        context.run_migrations()
else:
    with target_db.engine.connect() as connection:
        context.configure(**configure_args(connection=connection))
        with context.begin_transaction():
            context.run_migrations()
